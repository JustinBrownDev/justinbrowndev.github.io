function lineToPair(line) {
    const parts = String(line).split('|');
    const source = parts[1] || 'source';
    const text = parts.slice(3).join('|').trim();
    const words = text.split(/\s+/).filter(Boolean);
    const titleWords = words.slice(0, Math.min(6, Math.max(2, Math.ceil(words.length * 0.28))));
    const title = (titleWords.join(' ') || 'CODE NOTE').toUpperCase().slice(0, 58);
    const rest = words.slice(titleWords.length).join(' ');
    return [title, (rest || source).slice(0, 112)];
}

export const CODE_LORE_PAIRS = Object.freeze(CODE_LORE_LINES.map(lineToPair));
